// ⚠️ **الاختصار `@/` ماكانش بيتحلّ في الاختبارات خالص.** المشروع كله بيستخدمه
// (`tsconfig` فيه `paths`)، بس vitest مابيقراش من هناك — فأي ملف تحت
// الاختبار يستورد `@/…` **حقيقي** كان بيقع بـ:
//
//     Cannot find package '@/lib/…'
//
// وده ماكانش باين لأن المسارات المختبرة كانت بتستورد `@/…` **متبدّلة
// بالموك بس**، والموك بيتحط قبل ما الاستيراد يتحلّ. أول استيراد حقيقي
// (`lib/bosta/sync-cooldown` — ١٨ أغسطس) وقّع ٨ اختبارات مرة واحدة.
// ==========================================================================

import { defineConfig } from "vitest/config";
import { fileURLToPath } from "node:url";

export default defineConfig({
  resolve: {
    alias: {
      "@": fileURLToPath(new URL(".", import.meta.url)),
    },
  },
});
