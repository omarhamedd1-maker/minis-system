-- ==========================================================================
-- «باقة بوسطة» و«بوسطة مقدم» — من تصنيف «شحن» لتصنيف لوحده
-- (MONEY §٨.٦ — قرار عمر ١٧ سبتمبر)
-- --------------------------------------------------------------------------
-- ⚠️ **الباقة رصيد شحن مدفوع مقدم** (٥٠ أوردر بـ٤٥٠٠ · وباقة ٢٠) بيتستهلك
-- مع كل شحنة — ورسوم بوسطة على كل أوردر بتتخصم من الربح أصلًا. فتسجيلها
-- مصروف كمان = الفلوس بتتخصم مرتين. نفس الكلام على «بوسطة مقدم».
--
-- التصنيف «باقة بوسطة» مستثنى من حساب الربح في الكود
-- (`lib/profit-exclusions.ts`) — بس الصفوف القديمة متسجّلة «شحن»،
-- فلحد ما الملف ده يتشغّل هي لسه بتتخصم.
--
-- ⚠️ **بيغيّر التصنيف بس** — المبلغ والتاريخ والوصف وحركة الخزنة زي ما هم.
-- ==========================================================================


-- ===== خطوة ١: شوف اللي هيتنقل =====
-- على مينيز المفروض ٧ صفوف = ٢١,١٢٠:
--   باقة بوسطة ×٣ · باقة شحن · باقه شحن بوسطه · بوسطة مقدم ×٢
-- و«بوسطة» (٣٠٠) و«استلام بوسطة» (١٤٠) **مايتنقلوش**.
select t.name, e.expense_date, e.amount, e.description
from expenses e
join tenants t on t.id = e.tenant_id
where e.category = 'شحن'
  and (e.description ~ 'باق[ةه]' or e.description ~ 'مقدم')
order by t.name, e.expense_date;


-- ===== خطوة ٢: النقل =====
update expenses
set category = 'باقة بوسطة'
where category = 'شحن'
  and (description ~ 'باق[ةه]' or description ~ 'مقدم');


-- ===== تأكيد =====
select t.name, e.category, count(*) as "عدد", sum(e.amount) as "المبلغ"
from expenses e
join tenants t on t.id = e.tenant_id
where e.category in ('شحن', 'باقة بوسطة')
group by t.name, e.category
order by t.name, e.category;
