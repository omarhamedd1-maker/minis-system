-- فيه فرق بين حاجتين اتخلطوا لحد دلوقتي:
--   • أدمن البيزنس  = بيدير بيزنسه هو (المستخدمين، الإعدادات، الأوردرات)
--   • صاحب المنصة   = بيعمل بيزنسات جديدة ويوقف اشتراكات — ده إنت
--
-- عميل عنده كل صلاحيات بيزنسه **مايقدرش** يعمل بيزنس تاني ولا يشوف
-- البيزنسات التانية. الخانة دي هي الفرق.
-- ==========================================================================

alter table app_users
  add column if not exists is_platform_admin boolean not null default false;

comment on column app_users.is_platform_admin is
  'صاحب المنصة: يقدر يعمل بيزنسات ويدير اشتراكاتها. مش صلاحية بيزنس.';

-- عمر هو صاحب المنصة
update app_users
set is_platform_admin = true
where full_name = 'Omar Hamed'
  and tenant_id = '00000000-0000-0000-0000-000000000001';


