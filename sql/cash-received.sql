-- ==========================================================================
-- "وصلت" معناها بوسطة حوّلت الفلوس فعلًا — مش إن الأوردر اتسلّم
-- ==========================================================================
-- الغلط اللي كان موجود: الخانة كانت بتقول "وصلت" أول ما الأوردر يتسلّم.
-- وده مش صح — بوسطة بتحصّل من العميل وبتقعد بالفلوس **يوم أو أكتر** قبل ما
-- تحوّلها، وبتحوّلها بدفعات (تحويل أسبوعي). فالأوردر يبان إن فلوسه وصلت
-- وهي لسه في محفظة بوسطة.
--
-- وبقت تلات حالات بدل اتنين:
--   لسه          الشحنة في السكة
--   مع بوسطة     العميل دفع، والفلوس في محفظة بوسطة لسه ماتحوّلتش
--   وصلت         بوسطة حوّلت، وإنت أكّدت
--
-- ⚠️ ومحتاجة تأكيد يدوي بقصد: مسار محفظة بوسطة مقفول علينا (بيرجّع ٤٠١
-- لأن صلاحية المفتاح مابتشملش المحفظة)، فمفيش طريقة نعرف التحويل تلقائيًا.
-- ==========================================================================

alter table orders
  add column if not exists cash_received_at timestamptz;

create index if not exists orders_cash_pending
  on orders (tenant_id, cash_received_at)
  where cash_received_at is null;


