-- ==========================================================================
-- النسخة الاحتياطية — مهمة كرون واحدة كل يوم
-- --------------------------------------------------------------------------
-- بتنادي `/api/tasks/backup` اللي بيطلّع كل جدول في ملف CSV ويبعته على جروب
-- تليجرام بتاع البيزنس.
--
-- ⚠️⚠️ **النسخة اللي في نفس المكان مش نسخة.** لو الملفات اتحفظت جوّه نفس
-- حساب سوبابيز، أي حاجة تحصل للحساب هتوديها معاها. عشان كده الملفات بتطلع
-- **برّه السيستم خالص**، وبصيغة تتفتح من غيره.
--
-- ⚠️ **المفتاح مابيتكتبش هنا.** الأمر بيتاخد من مهمة المزامنة الموجودة
-- (`bosta-sync-15min`) وبيتبدّل فيه المسار بس — زي `weekly-digest` بالظبط.
--
-- ⚠️ **٣ الفجر بتوقيت مصر** = ١:٠٠ عالمي في الصيف. الساعة دي مختارة عشان
-- الشغل يكون واقف — النسخة بتقرا كل الجداول مرة واحدة، ووسط اليوم ده حِمل
-- على الداتابيز وقت ما الناس بتشتغل عليها.
--
-- ⚠️ **البيزنس اللي مالوش جروب بيتعدّى بهدوء** — مش عطل، ده إعداد لسه
-- مااتعملش. الجروب بيتظبّط من الإعدادات.
-- ==========================================================================

do $$
declare
  sync_cmd text;
begin
  select command into sync_cmd
  from cron.job
  where jobname = 'bosta-sync-15min';

  -- **مالقيناش مهمة المزامنة؟ نقف** — من غيرها مفيش مفتاح، وجدولة أمر ناقص
  -- معناها نسخة بتفشل كل يوم في صمت، وده أسوأ من مفيش نسخة: هتفتكر إن عندك
  -- واحدة.
  if sync_cmd is null then
    raise exception
      'مالقيتش مهمة المزامنة bosta-sync-15min — شوف sql/cron-jobs.sql الأول';
  end if;

  if exists (select 1 from cron.job where jobname = 'daily-backup') then
    perform cron.unschedule('daily-backup');
  end if;

  perform cron.schedule(
    'daily-backup',
    '0 1 * * *',
    replace(sync_cmd, '/api/bosta/sync', '/api/tasks/backup')
  );
end $$;


-- ===== التأكيد: المفروض تشوف daily-backup في القايمة =====
select jobname, schedule, active from cron.job order by jobname;


