-- ==========================================================================
-- خانتين جداد: كود الخصم + وقت السؤال بعد التسليم
-- --------------------------------------------------------------------------
-- ١) discount_code — كود الخصم اللي العميل استخدمه، بييجي من شوبيفاي مع
--    الأوردر. من غيره نقدر نقول «الخصم كسّب ولا خسّر» بس مش «أنهي كود».
--
--    ⚠️ الأوردرات القديمة هتفضل فاضية — الاستيراد بيضيف الجديد بس، والكود
--    مش متخزّن في أي مكان تاني عندنا. القايمة بتتملى مع الأوردرات الجاية.
--
-- ٢) followed_up_at — إمتى سألنا العميل «كل حاجة تمام؟» بعد التسليم.
--    الفاضي معناه لسه مااتسألش، فبيبان في الطابور.
-- ==========================================================================

alter table orders add column if not exists discount_code text;
alter table orders add column if not exists followed_up_at timestamptz;

-- طابور السؤال بيدوّر على المسلّم اللي لسه مااتسألش — الفهرس الجزئي ده
-- بيخلّيه يقرا الصفوف دي بس بدل الجدول كله
create index if not exists orders_followup_idx
  on orders (tenant_id, delivered_at)
  where followed_up_at is null;
