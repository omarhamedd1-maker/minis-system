-- ==========================================================================
-- الاسم المختصر لكل متجر
-- --------------------------------------------------------------------------
-- كل متجر بياخد اسم بالإنجليزي يبان في اللينك: `/login/minis`.
--
-- **وده نفسه اللي الساب دومين هيستخدمه بعدين** (`minis.الموقع.com`) — لما
-- الدومين يتشترى، الوسيط بيقرا الاسم من أول الدومين ويوجّهه لنفس المسار.
-- يعني الشغل ده مش مؤقت ومش هيتعاد.
-- ==========================================================================

alter table public.tenants
  add column if not exists slug text;

comment on column public.tenants.slug is
  'الاسم المختصر في اللينك — حروف إنجليزي صغيرة وأرقام وشرطة. بيبقى الساب دومين بعدين';

-- ==========================================================================
-- تعبئة الموجود
-- --------------------------------------------------------------------------
-- **مابنولّدش الاسم من اسم البيزنس** — أغلب الأسامي عربي، والترجمة الصوتية
-- بتطلّع أسامي وحشة والاسم ده بيبان لعملاء المتجر. فبنحط اسم مؤقت واضح
-- إنه مؤقت، وصاحب المنصة بيغيّره من شاشة البيزنسات.
-- ==========================================================================

update public.tenants
set slug = 'shop-' || substr(replace(id::text, '-', ''), 1, 6)
where slug is null;

-- ==========================================================================
-- التفرّد — **بعد التعبئة عشان مايفشلش على الصفوف الفاضية**
-- ==========================================================================

create unique index if not exists tenants_slug_unique
  on public.tenants (slug)
  where slug is not null;


