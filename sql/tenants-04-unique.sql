-- اكتشفناها في اختبار الاختراق: اسم الدور لازم يكون فريد في السيستم كله،
-- يعني بيزنسين مايقدروش يبقى عند كل واحد فيهم دور اسمه "Owner" — وده
-- بيمنع أي عميل جديد من أصله.
--
-- الصح إن الاسم يبقى فريد **جوّه البيزنس الواحد** مش في السيستم كله.
--
-- فحصنا باقي الخانات (رقم الأوردر، كود المنتج، تليفون العميل، اسم المنتج)
-- وكلها مافيهاش المشكلة دي.
-- ==========================================================================

-- ===== اسم الدور: فريد جوّه البيزنس بس =====
alter table roles drop constraint if exists roles_name_key;

create unique index if not exists roles_tenant_name_key
  on roles (tenant_id, name);


