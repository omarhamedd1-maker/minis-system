-- ==========================================================================
-- مفتاح ويب هوك لكل بيزنس
-- --------------------------------------------------------------------------
-- **المشكلة**: `BOSTA_WEBHOOK_KEY` سرّ واحد للمشروع كله ومكانه أسرار
-- سوبابيز. يعني كل مرة تربط بوسطة لبيزنس لازم حد يدخل اللوحة ويطلّع السرّ
-- ويلزقه في الرابط.
--
-- ولو خلّينا الشاشة تعرض الرابط جاهز بالسرّ ده عشان تريّح الخطوة دي،
-- **كل عميل هيشوف مفتاح كل العملاء** — والمفتاح ساعتها مابقاش معناه
-- «دي بوسطة»، بقى معناه «أي حد عدّى على الشاشة». ولو اتسرّب من واحد،
-- تغييره بيقع على الكل.
--
-- **الحل**: مفتاح عشوائي لكل بيزنس، السيستم بيولّده لوحده، والشاشة بتوري
-- كل واحد رابطه هو. **نفس الراحة بالظبط** — مفيش سوبابيز ولا سرّ بيتنقل —
-- والفرق إن كل واحد بيشوف بتاعه بس.
--
-- **وده مايضعّفش الأمان**: المفتاح أصلاً مالوش شغل غير إنه يقول «الرنّة
-- دي حقيقية». الحالة نفسها بنجيبها من بوسطة بمفتاح البيزنس نفسه، فاللي
-- بيرنّ مايقدرش يكتب حاجة. المطلوب إنه **مختلف** لكل واحد، مش إنه قوي.
--
-- ⚠️ **والمفتاح القديم بيفضل شغّال** — مينيز مظبوطة عليه من زمان، والمسار
-- بيقبل الاتنين. مافيش حاجة بتقع وقت النشر.
-- ==========================================================================

alter table tenant_credentials
  add column if not exists bosta_webhook_token text;

-- مفتاح لكل بيزنس مربوط ببوسطة دلوقتي (واللي يربط بعدين بياخد واحد وقتها)
update tenant_credentials
set bosta_webhook_token = encode(gen_random_bytes(16), 'hex')
where bosta_api_key is not null
  and bosta_webhook_token is null;

-- ماينفعش اتنين ياخدوا نفس المفتاح — ده أساس إن المفتاح يميّز البيزنس
create unique index if not exists tenant_credentials_bosta_webhook_token_key
  on tenant_credentials (bosta_webhook_token)
  where bosta_webhook_token is not null;

-- شوف النتيجة
select tenant_id,
       bosta_api_key is not null as "مربوط ببوسطة",
       bosta_webhook_token is not null as "ليه مفتاح"
from tenant_credentials;
