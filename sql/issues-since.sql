-- ==========================================================================
-- «مشاكل الأوردرات من تاريخ» — إعداد لكل بيزنس
-- --------------------------------------------------------------------------
-- الشاشات اللي بتدوّر على مشاكل (مراجعة الشحنات · صحة التشغيل · طوابير
-- الشغل) بتفضل تقول نفس المشاكل على أوردرات قديمة **خلاص اتصرّف فيها أو
-- اتقرر تتساب**. الرقم اللي بيفضل ثابت شهور بيتعلّم إنه يتتجاهل، وساعتها
-- التنبيه الحقيقي بيضيع وسطه.
--
-- ⚠️ **تاريخ في الإعدادات مش في الكود.** عمر بيحدده ويغيّره، وبيبان في
-- الشاشة إن فيه فلتر شغّال. التاريخ المكتوب في الكود بعد ٦ شهور محدش
-- بيعرف ليه اتحط (نفس درس استثناء المرتجعات — علامة على الأوردر مش تاريخ).
--
-- فاضي = اعرض كل حاجة (الوضع الافتراضي لأي بيزنس جديد).
-- ==========================================================================

alter table tenant_credentials
  add column if not exists issues_since date;

comment on column tenant_credentials.issues_since is
  'شاشات المشاكل بتعرض الأوردرات من التاريخ ده وبعده — فاضي = الكل';

-- مينيز: السيستم بدأ يشتغل على الفلوس من ١٨ يوليو ٢٠٢٦، واللي قبله
-- اتراجع واتقفل (قرار عمر ٢١ سبتمبر)
update tenant_credentials
set issues_since = date '2026-07-18'
where tenant_id = '00000000-0000-0000-0000-000000000001'
  and issues_since is null;


-- ===== تأكيد =====
select t.name, c.issues_since as "المشاكل من"
from tenants t
left join tenant_credentials c on c.tenant_id = t.id
order by t.name;


