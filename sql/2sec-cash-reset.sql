-- ⚠️⚠️⚠️ تصفير خزنة ٢ سِك والبدء من نضيف — ملف خطير، اقراه كله الأول
-- ==========================================================================
--
-- ده الملف الوحيد في المشروع اللي بيمسح حركات خزنة. وده **مخالف لقاعدة
-- السيستم** (MONEY §٦.٢: الحركات بتتلغى بحركة عكسية، مابتتمسحش) —
-- والقاعدة دي موجودة عشان سبب: الحركة الممسوحة مافيش حد يعرف إنها كانت
-- موجودة، ومفيش طريق رجوع.
--
-- عمر طلبه صراحة يوم ٧ نوفمبر ٢٠٢٦: «احذف كل الحركات الحالية واشتغل من
-- أول النهاردة على نضيف».
--
-- ⚠️ **مفيش تراجع.** السطور الممسوحة مش هترجع. لو عايز نسخة قبل المسح،
-- شغّل الخطوة ١ وصدّر النتيجة لملف **قبل** أي حاجة تانية.
--
-- اللي هيتمسح: ٩٩ حركة خزنة لـ٢ سِك (الرصيد الحالي −٤٬٨٠٠)
-- اللي **مش** هيتمسح: الأوردرات · المصاريف · التحويلات · المنتجات
-- ==========================================================================

-- ===== ١) خُد نسخة قبل أي حاجة — صدّر النتيجة دي لملف =====
select id, transaction_date, direction, amount, source_type, description,
       related_order_id, related_expense_id, related_payout_id, reversal_of,
       created_by_name, created_at
from cash_transactions
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657'
order by transaction_date, created_at;

-- ===== ٢) اللي هيتمسح بالأرقام =====
select source_type,
       count(*) as عدد,
       sum(case when direction = 'in'  then amount else 0 end) as داخل,
       sum(case when direction = 'out' then amount else 0 end) as خارج
from cash_transactions
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657'
group by source_type
order by source_type;

-- ===== ٣) فُك الروابط الأول =====
-- ⚠️ الترتيب مهم: الجداول اللي **بتشاور** على الحركة لازم تتفك قبلها،
-- وإلا المسح بيفشل على مفتاح أجنبي (CONTEXT قاعدة ٨).
update courier_payouts
set cash_transaction_id = null
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657';

-- الحركة العكسية بتشاور على حركة تانية في نفس الجدول
update cash_transactions
set reversal_of = null
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657'
  and reversal_of is not null;

-- ===== ٤) المسح =====
delete from cash_transactions
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657';

-- ===== ٥) الرصيد الافتتاحي =====
-- ⚠️ **غيّر الرقم ده للفلوس اللي في إيدك فعلًا النهاردة.**
-- سايبه صفر بقصد — ما بخمّنش فلوس. لو الخزنة فاضية فعلًا سيبه صفر.
-- والتاريخ لازم يكون **قبل** أول حركة جاية، فخلّيه امبارح.
insert into cash_transactions
  (tenant_id, direction, amount, source_type, transaction_date, description, created_by_name)
values
  ('f2833051-6e44-4393-9878-21406986b657', 'in', 0, 'opening',
   date '2026-11-07', 'رصيد افتتاحي', 'بداية جديدة');

-- ===== ٦) اتأكد =====
select count(*) as حركات,
       sum(case when direction = 'in' then amount else -amount end) as الرصيد
from cash_transactions
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657';

