-- ==========================================================================
-- سبب رجوع الشحنة
-- --------------------------------------------------------------------------
-- الأوردر بيرجع ومفيش خانة بتقول ليه. النتيجة إن سؤال «إحنا بنخسر ليه؟»
-- إجابته تخمين — رغم إن نسبة الرجوع في مينيز **١٧٪** وقيمة البضاعة
-- الراجعة **٨٣ ألف جنيه**.
--
-- عمود واحد بيحوّل الرقم ده لإجابة: عنوان مش واضح؟ العميل مش بيرد؟ غيّر
-- رأيه؟ خارج التغطية؟ كل واحد منهم ليه علاج مختلف تمامًا.
--
-- **بيتساب فاضي بقصد.** الشحنات اللي رجعت قبل كده مالهاش سبب متسجّل،
-- ومحدش هيفتكرها. الإحصائية بتبدأ من دلوقتي.
-- ==========================================================================

alter table public.orders
  add column if not exists return_reason text;

comment on column public.orders.return_reason is
  'سبب رجوع الشحنة — قيمة من القايمة في lib/return-reasons.ts. فاضي = مااتسجّلش';

-- الفلترة بتحصل على الراجع بس، فالفهرس جزئي — أصغر وأسرع
create index if not exists orders_return_reason_idx
  on public.orders (tenant_id, return_reason)
  where return_reason is not null;

