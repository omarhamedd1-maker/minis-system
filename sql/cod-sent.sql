-- ==========================================================================
-- رقم التحصيل اللي **إحنا** بعتناه لبوسطة — منفصل عن اللي بوسطة شايلاه
-- ==========================================================================
-- خانة `bosta_cod` بتتكتب من مكانين:
--
--   ١. وقت عمل الشحنة — بالرقم اللي إحنا حسبناه (`computeCod`)
--   ٢. **والمزامنة بتكتب فوقها** كل ربع ساعة بالرقم اللي بوسطة بترجّعه:
--
--        if (cod !== Number(o.bosta_cod ?? 0)) changes.bosta_cod = cod;
--
-- يعني لو بوسطة رجّعت رقم تاني — أو صفر — **رقمنا الأصلي بيتمسح ومفيش
-- حاجة تفتكره**. وساعتها مايبقاش فيه طريقة نعرف بيها الشحنة اتعملت بكام.
--
-- ده اتكشف ١٧ أغسطس ٢٠٢٦ وإحنا بندوّر على أوردرين (١٤١٩ و١٤١٥، ٢٠٣٧ ج
-- لكل واحد) تحصيلهم عند بوسطة صفر. البنود كانت سليمة قبل الشحنة بيوم،
-- ومفيش تعديل دفع متسجّل، والشحنة اتعملت من عندنا (الملاحظات والمرجع
-- والوصف بتوعنا) — ومع كده مقدرناش نعرف اتبعتت بكام، لأن الرقم اتمسح.
--
-- الخانة الجديدة **مابتتلمسش من المزامنة أبدًا**. بتتكتب مرة وقت عمل
-- الشحنة، وتتحدّث لما إحنا بنبعت تعديل تحصيل لبوسطة. وبكده المقارنة
-- بتبقى بين رقمنا المحفوظ ورقم بوسطة، مش بين رقم بوسطة ونفسه.
-- ==========================================================================

alter table public.orders
  add column if not exists bosta_cod_sent numeric;

comment on column public.orders.bosta_cod_sent is
  'التحصيل اللي إحنا بعتناه لبوسطة وقت عمل الشحنة — المزامنة مابتلمسهوش';


