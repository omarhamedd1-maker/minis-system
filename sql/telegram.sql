-- ليه تليجرام مش واتساب: واتساب مابيسمحش لأي سيستم يبعت غير بحساب Business
-- API موثّق وقوالب رسايل متوافق عليها يدوي — أيام لأسابيع وتكلفة شهرية.
-- تليجرام بوت مجاني وبيشتغل في دقايق. لما نبيع لعملاء حقيقيين ونحتاج نبعت
-- **للعملاء نفسهم** ساعتها الواتساب يبقى مبرّر.
--
-- المفاتيح جوّه tenant_credentials (الجدول المقفول) مش في متغيرات البيئة،
-- عشان كل بيزنس يبعت على جروبه هو.
--
-- إزاي عمر يجيبهم:
--   ١. في تليجرام كلّم @BotFather واعمل /newbot → هيديك التوكن
--   ٢. اعمل جروب، ضيف البوت فيه
--   ٣. ابعت أي رسالة في الجروب، وبعدين افتح:
--      https://api.telegram.org/bot<التوكن>/getUpdates
--      وخد الرقم اللي في chat.id (بيبدأ بسالب للجروبات)
--   ٤. حطهم في شاشة الإعدادات
-- ==========================================================================

alter table tenant_credentials
  add column if not exists telegram_bot_token text,
  add column if not exists telegram_chat_id text;


