-- ==========================================================================
-- خلاصة الأسبوع — مهمة كرون واحدة كل جمعة
-- --------------------------------------------------------------------------
-- بتنادي `/api/tasks/weekly` اللي بيلف على كل بيزنس شغّال ويبعت رسالة واحدة
-- على الموبايل وتليجرام: مبيعات الأسبوع وصافيه **مقارنة بالأسبوع اللي فاته**،
-- ونسبة الرجوع، واللي واقف دلوقتي.
--
-- ⚠️⚠️ **المفتاح مابيتكتبش هنا.** الأمر بيتاخد من مهمة المزامنة الموجودة
-- (`bosta-sync-15min`) وبيتبدّل فيه المسار بس — نفس طريقة `tasks-tick-15min`.
-- كده المفتاح مايظهرش في أي ملف ولا يتلزق في محرر SQL.
--
-- ⚠️ **الجمعة ٨ مساءً بتوقيت مصر** = ١٨:٠٠ عالمي في الصيف. pg_cron شغال
-- بالتوقيت العالمي والفرق بيتغيّر مع التوقيت الصيفي، يعني في الشتا هتوصل
-- ٧ مساءً. الفرق ساعة مش فارق هنا.
--
-- ⚠️ **والأسبوع الفاضي مابيتبعتش** — المسار بيتخطّاه لوحده، فمافيش رسالة
-- بأصفار كل جمعة (والرسالة اللي بتتكرر بأصفار بتتقفل بعد تلات مرات).
-- ==========================================================================

do $$
declare
  sync_cmd text;
begin
  select command into sync_cmd
  from cron.job
  where jobname = 'bosta-sync-15min';

  -- **مالقيناش مهمة المزامنة؟ نقف** — من غيرها مفيش مفتاح، وجدولة أمر ناقص
  -- معناها مهمة بتفشل كل جمعة في صمت.
  if sync_cmd is null then
    raise exception
      'مالقيتش مهمة المزامنة bosta-sync-15min — شوف sql/cron-jobs.sql الأول';
  end if;

  if exists (select 1 from cron.job where jobname = 'weekly-digest') then
    perform cron.unschedule('weekly-digest');
  end if;

  perform cron.schedule(
    'weekly-digest',
    '0 18 * * 5',
    replace(sync_cmd, '/api/bosta/sync', '/api/tasks/weekly')
  );
end $$;


-- ===== التأكيد: المفروض تشوف weekly-digest في القايمة =====
select jobname, schedule, active from cron.job order by jobname;


