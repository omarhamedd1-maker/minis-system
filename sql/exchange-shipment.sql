-- ==========================================================================
-- شحنة التبديل
-- --------------------------------------------------------------------------
-- الأوردر اتسلّم، والعميل عايز يبدّل: بوسطة بتروح له بالحاجة الجديدة وتاخد
-- منه القديمة في نفس الرحلة. نوع الخدمة عند بوسطة ٣٠ (Exchange).
--
-- بنخزّن رقم تتبعها لوحده — مش في `bosta_tracking` (دي الشحنة الأصلية) ولا
-- في `return_tracking` (دي المرتجع اللي مالوش بديل). التلاتة ممكن يبقوا
-- موجودين على نفس الأوردر في نفس الوقت.
-- ==========================================================================

alter table public.orders
  add column if not exists exchange_tracking text,
  add column if not exists exchange_note text;

comment on column public.orders.exchange_tracking is
  'رقم تتبع شحنة التبديل عند بوسطة (نوع ٣٠)';
comment on column public.orders.exchange_note is
  'إيه اللي راح للعميل وإيه اللي رجع منه — بيتكتب وقت عمل الشحنة';

