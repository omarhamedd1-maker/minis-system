-- ==========================================================================
-- ⚠️ تصفير تحويلات ٢ سِك — الشغل يبدأ من أول إيصال جديد
-- ==========================================================================
--
-- الكشف اترفع قبل ما نقرر نلغيه، فدخل ١٢٦ تحويل تاريخي (يناير ← ٥
-- نوفمبر ٢٠٢٦) و٣٨٠ بند رسوم. وعمر عايز التحويلات تبدأ من نضيف.
--
-- ⚠️ **مفيش تراجع** — زي ملف الخزنة. بس الخسارة هنا أقل بكتير: كل ده
-- موجود في كشف المحفظة عند بوسطة، وينفع يترفع تاني في أي وقت.
--
-- ⚠️ **ولو رفعته تاني بعد كده، هيعمل ١٢٦ حركة خزنة بـ٣٠٣٬٤٧٨ جنيه** —
-- الكود الجديد بيعمل الحركة لوحده. فما ترفعوش إلا لو ده اللي إنت عايزه.
--
-- اللي اتقاس قبل المسح (٧ نوفمبر ٢٠٢٦):
--   ١٢٦ تحويل — ١٠٢ «محتاج مراجعة» و٢٤ «متطابق» (كلهم بالكود القديم)
--   ٣٨٠ بند رسوم
--   صفر رابط أوردر · صفر أوردر متعلّم عليه ← فالمسح مالوش أثر جانبي
-- ==========================================================================

-- ===== ١) شوف اللي هيتمسح =====
select source, status, count(*) as عدد, sum(net_amount) as المجموع
from courier_payouts
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657'
group by source, status;

select category, count(*) as عدد, sum(amount) as المجموع
from courier_fee_lines
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657'
group by category
order by abs(sum(amount)) desc;

-- ===== ٢) الروابط الأول =====
-- ⚠️ اللي بيشاور على التحويل قبل التحويل نفسه (CONTEXT قاعدة ٨).
-- المقاس بيقول صفر، بس السطور دي بتخلّي الملف يشتغل في أي وقت.
delete from courier_payout_orders
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657';

update cash_transactions
set related_payout_id = null
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657'
  and related_payout_id is not null;

-- ===== ٣) التحويلات =====
delete from courier_payouts
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657';

-- ===== ٤) بنود الرسوم =====
-- ⚠️ **دي اختيارية.** لو عايز تفصيل الرسوم التاريخي يفضل في تاب الرسوم،
-- سيب السطر ده متعلّق عليه. بس ساعتها هتبقى عندك رسوم من غير تحويلاتها.
delete from courier_fee_lines
where tenant_id = 'f2833051-6e44-4393-9878-21406986b657';

-- ===== ٥) اتأكد =====
select
  (select count(*) from courier_payouts
    where tenant_id = 'f2833051-6e44-4393-9878-21406986b657') as تحويلات,
  (select count(*) from courier_fee_lines
    where tenant_id = 'f2833051-6e44-4393-9878-21406986b657') as بنود_رسوم,
  (select count(*) from cash_transactions
    where tenant_id = 'f2833051-6e44-4393-9878-21406986b657') as حركات_خزنة,
  (select coalesce(sum(case when direction = 'in' then amount else -amount end), 0)
     from cash_transactions
    where tenant_id = 'f2833051-6e44-4393-9878-21406986b657') as الرصيد;

-- المفروض: تحويلات ٠ · بنود رسوم ٠ · حركات خزنة ١ (الافتتاحي) · الرصيد زي ما حطيته
