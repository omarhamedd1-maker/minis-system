-- الخانة بتسجّل آخر يوم نبّهنا فيه — عشان التنبيه يبقى **مرة واحدة في اليوم**
-- مش كل ١٥ دقيقة مع كل مزامنة.
--
-- وأول ما الحالة تتغيّر لأي حاجة تانية (مؤكد، ملغي، أي حاجة) التنبيه بيوقف
-- لوحده — مافيش حاجة محتاجة تتصفّر.
-- ==========================================================================

