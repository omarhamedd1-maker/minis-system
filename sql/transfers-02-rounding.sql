-- ==========================================================================
-- فرق التقريب على التحويل + درجة الثقة في ربط الأوردرات
-- --------------------------------------------------------------------------
-- ⚠️⚠️ **الحركات اليدوية مكتوبة بالجنيه الصحيح.** عمر بيسجّل ٤,٠٤٨ والتحويل
-- الحقيقي ٤,٠٤٨٫٠٤. الفرق ده **مش خطأ مطابقة — هو فرق حقيقي في الرصيد**،
-- ولو ماتسجّلش الرصيد بيفضل ناقص القروش دي للأبد.
--
-- القياس على مينيز (١٨ سبتمبر): ٢١ تحويل فروقهم أقل من جنيه، ومجموعهم
-- حوالي ١٠ جنيه على ٧ شهور.
--
-- ⚠️ **العمود ده بيتسجّل ومابيعملش حركة** — التسوية قرار عمر، والاستيراد
-- مايغيّرش رصيد من نفسه (§٩.١).
--
-- و`match_confidence`: ربط الأوردرات اتعمل إزاي —
--   'exact'  مجموعهم بالمليم زي التحويل
--   'likely' نافذة زمنية (محاولة تانية بعد الفشل) — **مرجّح مش مؤكد**
-- ==========================================================================

alter table courier_payouts
  add column if not exists rounding_diff numeric not null default 0,
  add column if not exists match_confidence text;

comment on column courier_payouts.rounding_diff is
  'فرق التقريب بين مبلغ التحويل والحركة اليدوية — فرق حقيقي في الرصيد';
comment on column courier_payouts.match_confidence is
  'exact = بالمليم · likely = بنافذة زمنية، مرجّح مش مؤكد';


-- ===== تأكيد =====
select
  count(*)                                   as "تحويلات",
  coalesce(sum(rounding_diff), 0)            as "مجموع فروق التقريب",
  count(*) filter (where match_confidence = 'likely') as "ربط مرجّح"
from courier_payouts;


