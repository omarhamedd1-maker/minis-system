const NAMES: Record<string, string> = {
  search: "بحث",
  work: "الشغل",
  orders: "الأوردرات",
  tasks: "التاسكات",
  inbox: "الرسايل",
  reports: "تقارير",
  customers: "العملاء",
  products: "المنتجات",
  suppliers: "الموردين",
  expenses: "المصاريف",
  cash: "الفلوس",
  users: "المستخدمون",
  settings: "الإعدادات",
  platform: "البيزنسات",
  notify: "الإشعارات",
};

/** `null` = دي الرئيسية، اعرض التحية */
export function pageTitle(pathname: string | null | undefined): string | null {
  const path = String(pathname ?? "").split("?")[0];
  const first = path.split("/").filter(Boolean)[0];
  if (!first) return null;
  return NAMES[first] ?? null;
}
