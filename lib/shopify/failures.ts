/** البيزنس ده لسه ماربطش متجر */
export const NOT_LINKED_ERROR = "البيزنس ده لسه مربطش متجر شوبيفاي";

/** شوبيفاي ردّت ٤٠٢ — المتجر نفسه مقفول */
export const SHOP_CLOSED_ERROR =
  "متجر شوبيفاي مقفول — فاتورة شوبيفاي مش مدفوعة، والمتجر مقفول قدام العملاء كمان";

/** الأسباب اللي مابتتبعتش إشعار */
export const SILENT_IMPORT_REASONS = [NOT_LINKED_ERROR, SHOP_CLOSED_ERROR];

/**
 * السبب ده يستاهل إشعار؟
 *
 * ⚠️ **المقارنة ببداية النص مش بتساويه** — السبب بيتكتب زي ما شوبيفاي ردّت
 * بيه وساعات بيتلزق عليه تفصيل زيادة، والنسخة اللي بتقارن بالتساوي كانت
 * هتبعت الإشعار أول ما حرف يزيد.
 */
export function importAlertNeeded(reason: string): boolean {
  const text = String(reason ?? "").trim();
  if (!text) return false;
  return !SILENT_IMPORT_REASONS.some((r) => text.startsWith(r));
}
