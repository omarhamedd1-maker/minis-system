// ==========================================================================
// علامات على الأوردر قبل ما تشحنه
// --------------------------------------------------------------------------
// الشحنة اللي بترجع بتكلّف شحن ورسوم وبضاعة اتحركت مرتين، والقرار اللي بيمنع
// ده بيتاخد **قبل** ما البوليصة تتطبع. والمعلومات اللي بتقول «دي محتاجة نظرة»
// موجودة عندك خلاص: العنوان، وتاريخ العميل، وحجم الأوردر.
//
// ⚠️⚠️ **دي تنبيهات مش موانع — بقرار عمر.** الأوردر بيفضل يتشحن عادي، والعلامة
// بتقوله «بصّ على دي الأول». السيستم اللي بيوقف الشغل بيتلف عليه بعد أسبوع.
//
// ⚠️ **والعلامة اللي بتظهر على كل أوردر مالهاش قيمة.** كل حد هنا ليه سبب
// محدد ورقم وراه، ولو طلعت على نص الأوردرات يبقى الحد غلط مش الأوردرات.
//
// **الملف ده صافي** — مافيش شبكة ولا قاعدة بيانات.
// ==========================================================================

/** الحالات اللي لسه ينفع تتصرّف فيها قبل الشحن */
const BEFORE_SHIPPING = ["new", "confirmed", "packed"];

/**
 * ⚠️ **العنوان الأقصر من كده غالبًا ناقص.**
 *
 * «شارع ٩ المعادي» = ١٥ حرف والمندوب مش هيلاقيه. والرقم مهم بنفس القد —
 * عنوان من غير أي رقم معناه مافيش رقم عمارة ولا دور.
 */
export const SHORT_ADDRESS = 25;

/** الأوردر الأكبر من كده من عميل جديد بيستاهل مكالمة */
export const BIG_ORDER = 3000;

/** كام إلغاء قبل كده عشان العلامة تظهر */
export const CANCELS_TO_FLAG = 2;

export type FlagOrder = {
  orderStatus: string | null;
  /** إجمالي الأوردر بالفلوس */
  total: number;
  address?: string | null;
  /** أوردرات العميل السابقة (من غير ده) */
  previousOrders?: number;
  /** كام منهم رجع */
  previousReturns?: number;
  /** كام أوردر اتلغى للعميل ده قبل كده */
  previousCancels?: number;
  /**
   * كام أوردر تاني على **نفس التليفون في نفس اليوم** (من غير ده).
   *
   * ⚠️ **التليفون مش العنوان** — العنوان بيتكتب بألف طريقة («٩ شارع
   * المعادي» و«٩ ش المعادى») فمقارنته حرف بحرف بتفوّت أغلب التكرار.
   * التليفون بيتكتب بطريقة واحدة.
   */
  sameDayOthers?: number;
};

export type OrderFlag = {
  key: "address" | "returner" | "big_new" | "canceller" | "same_day";
  /** الجملة اللي بتظهر */
  text: string;
  /** إيه اللي ممكن يتعمل — من غير أمر */
  why: string;
};

/** العنوان فيه رقم؟ */
function hasDigit(text: string): boolean {
  return /[0-9٠-٩]/.test(text);
}

/**
 * علامات الأوردر.
 *
 * بيرجّع قايمة فاضية للأوردر اللي مافيهوش حاجة — والفاضي هو الطبيعي.
 */
export function orderFlags(o: FlagOrder): OrderFlag[] {
  // بعد ما يروح لبوسطة، الكلام ده عدّى
  if (!BEFORE_SHIPPING.includes(String(o.orderStatus))) return [];

  const flags: OrderFlag[] = [];

  const address = String(o.address ?? "").trim();
  if (address.length < SHORT_ADDRESS || !hasDigit(address)) {
    flags.push({
      key: "address",
      text: address ? "العنوان مختصر أو مافيهوش أرقام" : "مافيش عنوان",
      why: "المندوب بيدوّر ومايلاقيش، والشحنة بترجع — رقم العمارة والدور بيفرقوا",
    });
  }

  const prev = Math.max(0, Number(o.previousOrders ?? 0));
  const returns = Math.max(0, Number(o.previousReturns ?? 0));

  if (returns > 0) {
    flags.push({
      key: "returner",
      text:
        returns === 1
          ? "العميل ده رجّع أوردر قبل كده"
          : `العميل ده رجّع ${returns} أوردرات قبل كده`,
      why: "مكالمة تأكيد قبل الشحن بتوفّر شحنة رايحة جاية",
    });
  }

  // ⚠️ **الإلغاء مش الرجوع.** الإلغاء بيضيّع وقت قبل ما الشحنة تتعمل، فتكلفته
  // أقل — عشان كده بنستنى يتكرر بدل ما نرن من أول مرة.
  const cancels = Math.max(0, Number(o.previousCancels ?? 0));
  if (cancels >= CANCELS_TO_FLAG) {
    flags.push({
      key: "canceller",
      text: `اتلغاله ${cancels} أوردرات قبل كده`,
      why: "الأوردر اللي بيتلغى بعد التجهيز بياكل وقت ومكان في العربية",
    });
  }

  const sameDay = Math.max(0, Number(o.sameDayOthers ?? 0));
  if (sameDay > 0) {
    flags.push({
      key: "same_day",
      text: `نفس التليفون عليه ${sameDay + 1} أوردرات النهاردة`,
      why: "غالبًا نفس الأوردر اتبعت مرتين، وشحن الاتنين بيرجّع واحد",
    });
  }

  // ⚠️ **الكبير من عميل جديد بس** — العميل اللي اشترى قبل كده وأوردره كبير
  // ده أحسن عميل عندك، ووضع علامة عليه بيخلّي العلامات كلها ضوضاء.
  if (prev === 0 && Number(o.total) >= BIG_ORDER) {
    flags.push({
      key: "big_new",
      text: `أوردر كبير (${Math.round(Number(o.total))} ج) من عميل أول مرة`,
      why: "الأوردر الكبير اللي يرجع بيوجع مرتين — تأكيد بمكالمة بيقلّل ده",
    });
  }

  return flags;
}

/**
 * العلامات اللي وراها تاريخ فعلي — مش شكل الأوردر.
 *
 * ⚠️⚠️ **العنوان القصير لوحده مش أوردر مشبوه.** على داتا مينيز العنوان
 * بيرن على نُص الأوردرات تقريبًا، فلو دخل في القايمة، القايمة بتبقى هي
 * قايمة الأوردرات كلها ومحدش يبص عليها تاني.
 */
const HISTORY_FLAGS = ["returner", "canceller", "same_day"];

/**
 * الأوردر ده يستاهل وقفة قبل ما يتشحن؟
 *
 * ⚠️ **علامة تاريخ واحدة، أو علامتين أيًا كانوا.** العلامة الشكلية لوحدها
 * (عنوان قصير · أوردر كبير) مابتوقفش أوردر.
 */
export function worthChecking(flags: OrderFlag[]): boolean {
  if (flags.some((f) => HISTORY_FLAGS.includes(f.key))) return true;
  return flags.length >= 2;
}

/** «رجّع أوردر قبل كده · العنوان مختصر» */
export function flagLine(flags: OrderFlag[]): string {
  return flags.map((f) => f.text).join(" · ");
}
