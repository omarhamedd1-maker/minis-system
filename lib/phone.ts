// كانت فيه نسختين مختلفتين: مطابقة بوسطة بتاخد آخر ٩ أرقام، ومطابقة
// شوبيفاي آخر ١٠ — نفس الرقم بيطلع منهما مفتاحين مختلفين، وأي حاجة
// تعدّي بين المسارين بتضيع. بقى مكان واحد ومفتاح واحد (٢٤ أغسطس).
//
// **آخر ٩ أرقام**: بتشيل مفتاح الدولة (+20 · 0020) والصفر البادئ مع
// بعض — فالأشكال كلها بتطلع لنفس المفتاح.
// ==========================================================================

export function phoneKey(phone: string | null | undefined): string {
  const digits = String(phone ?? "").replace(/\D/g, "");
  return digits.length >= 9 ? digits.slice(-9) : "";
}
