// التنبيه اللي بيتبعت مرة واحدة فعلًا
// --------------------------------------------------------------------------
// ⚠️⚠️ **`tag` مابيمنعش الإرسال.** هو خانة في رسالة الويب بوش بتخلّي
// **الجهاز** يستبدل الإشعار القديم بالجديد على الشاشة — الرسالة بتتبعت
// برضه، والتليفون بيرن برضه.
//
// يعني أي تنبيه «مرة في اليوم» مربوط بتاج كان بيتبعت **كل ربع ساعة طول
// اليوم** — ٩٦ مرة. عمر اتضرب بده يوم ٢٠ أغسطس ٢٠٢٦: تنبيه المبيعات
// الواقعة فضل يرن كل ربع ساعة من الفجر.
//
// **الحل**: سجل بيقول «التاج ده اتبعت خلاص». الكتابة هي اللي بتحجز — لو
// اتنين اشتغلوا في نفس الثانية، واحد بس بيكتب والتاني بيتخطّى.
//
// ⚠️ **والجدول لو مش موجود، بنبعت.** التنبيه اللي مايوصلش أوحش من تنبيه
// اتكرر — بس السجل ده بالظبط هو اللي بيمنع التكرار، فلازم يتعمل.
// ==========================================================================

import type { SupabaseClient } from "@supabase/supabase-js";

export type OnceResult =
  /** اتحجز دلوقتي — ابعت */
  | { send: true }
  /** اتبعت قبل كده — متبعتش */
  | { send: false; reason: "already" }
  /** الجدول مش موجود — ابعت وسيبها */
  | { send: true; reason: "no_table" };

/**
 * بيحجز التاج ده للبيزنس ده.
 *
 * بيرجّع `send: true` **مرة واحدة بس** لكل تاج. أي نداء بعد كده على نفس
 * التاج بيرجّع `false`.
 *
 * ⚠️ **الحجز قبل الإرسال مش بعده** — لو حجزنا بعد ما نبعت، اللفتين اللي
 * بيشتغلوا مع بعض بيبعتوا الاتنين قبل ما حد يكتب.
 */
export async function reserveOnce(
  db: SupabaseClient,
  tenantId: string,
  tag: string
): Promise<OnceResult> {
  try {
    const { error } = await db
      .from("notification_log")
      .insert({ tenant_id: tenantId, tag });

    if (!error) return { send: true };

    // ⚠️ **23505 = الصف موجود** — ده مش عطل، ده بالظبط اللي بندوّر عليه
    const code = (error as { code?: string }).code;
    if (code === "23505") return { send: false, reason: "already" };

    // الجدول لسه مااتعملش؟ نبعت — التنبيه اللي مايوصلش أوحش من المكرر
    return { send: true, reason: "no_table" };
  } catch {
    return { send: true, reason: "no_table" };
  }
}

/**
 * تاج بيتغيّر كل يوم — «مرة في اليوم».
 *
 * ⚠️ **باليوم المصري** — التاج باليوم العالمي بيتغيّر الساعة ٢ بالليل
 * بتوقيت مصر، فالتنبيه بيتبعت مرتين في نفس الليلة.
 */
export function dailyTag(name: string, at: Date): string {
  const day = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Africa/Cairo",
  }).format(at);
  return `${name}-${day}`;
}
