import { describe, it, expect } from "vitest";
import { shortLogText, bostaStateAr } from "./log-text";

const short = (s: string) => shortLogText(s, "1367");

describe("سطر السجل في صفحة الأوردر", () => {
  it("الحالة", () => {
    expect(short("غيّر حالة أوردر 1367 لـ مؤكد")).toBe("الحالة: مؤكد");
  });

  it("حالة بوسطة بتترجم والقديمة بتتشال", () => {
    expect(
      short("شحنة أوردر 1364 عند بوسطة: Picked up (كانت Received at warehouse)")
    ).toBe("بوسطة: المندوب استلمها");
  });

  it("حالة بوسطة من غير قديمة", () => {
    expect(short("شحنة أوردر 1364 عند بوسطة: Delivered")).toBe("بوسطة: اتسلّمت");
  });

  it("حالة بوسطة مش في القايمة بتتعرض زي ما هي", () => {
    expect(short("شحنة أوردر 1364 عند بوسطة: Something New")).toBe(
      "بوسطة: Something New"
    );
    expect(bostaStateAr("Whatever")).toBe("Whatever");
  });

  it("التحصيل", () => {
    expect(short("تحصيل أوردر 1374 عند بوسطة اتغيّر من 739 لـ 1388")).toBe(
      "التحصيل: 739 ← 1388"
    );
  });

  it("الشحن والخصم", () => {
    expect(short("غيّر شحن أوردر 1365 لـ 0")).toBe("الشحن: 0");
    expect(short("غيّر خصم أوردر 1367 لـ 100")).toBe("الخصم: 100");
  });

  it("طريقة الدفع", () => {
    expect(short("غيّر طريقة الدفع لأوردر 1366 (مدفوع 0)")).toBe(
      "طريقة الدفع (مدفوع 0)"
    );
  });

  it("شوبيفاي وبوسطة", () => {
    expect(short("تعديل أوردر 1378 اتبعت لشوبيفاي")).toBe("اتبعت لشوبيفاي");
    expect(short("بعت أوردر لبوسطة كشحنة")).toBe("اتبعت لبوسطة");
  });

  it("الباقي بيتشال منه رقم الأوردر وحرف الجر", () => {
    expect(short("عدّل كمية بند في أوردر 1367")).toBe("عدّل كمية بند");
    expect(short("مسح منتج من أوردر 1367")).toBe("مسح منتج");
    expect(short("أضاف منتج لأوردر 1367")).toBe("أضاف منتج");
  });

  it("⚠️ رقم أوردر تاني مايتشالش", () => {
    expect(short("ربط شحنة 999 بأوردر 1400")).toBe("ربط شحنة 999 بأوردر 1400");
  });

  it("⚠️ الرقم اللي جوّه رقم أطول مايتشالش", () => {
    expect(shortLogText("عدّل كمية بند في أوردر 13670", "1367")).toBe(
      "عدّل كمية بند في أوردر 13670"
    );
  });

  it("النص اللي مالوش علاقة بيرجع زي ما هو", () => {
    expect(short("سجّل مصروف تصنيع وخامات بمبلغ 500")).toBe(
      "سجّل مصروف تصنيع وخامات بمبلغ 500"
    );
  });

  it("الفاضي بيفضل فاضي والناقص مابيوقعش", () => {
    expect(shortLogText(null, "1367")).toBe("");
    expect(shortLogText("عدّل كمية بند", null)).toBe("عدّل كمية بند");
  });

  it("⚠️ مابيرجّعش فاضي لو القص أكل السطر كله", () => {
    expect(shortLogText("أوردر 1367", "1367")).toBe("أوردر 1367");
  });
});
