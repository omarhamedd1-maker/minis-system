/**
 * ==========================================================================
 * «مشاكل الأوردرات من تاريخ» — فلتر واحد لكل شاشات المشاكل
 * --------------------------------------------------------------------------
 * ⚠️⚠️ **الرقم اللي بيفضل ثابت شهور بيتعلّم إنه يتتجاهل.** شاشات المشاكل
 * (مراجعة الشحنات · صحة التشغيل · طوابير الشغل) كانت بتعيد نفس المشاكل
 * على أوردرات قديمة اتقرر تتساب، فالتنبيه الحقيقي بيضيع وسطها.
 *
 * ⚠️ **التاريخ إعداد مش رقم في الكود** (`tenant_credentials.issues_since`).
 * التاريخ المكتوب في الكود محدش بيعرف بعد شهور ليه اتحط — نفس الدرس بتاع
 * استثناء المرتجعات (علامة على الأوردر، مش تاريخ مخبّي).
 *
 * ⚠️ **والفلتر لازم يبان في الشاشة** — الصفحة اللي بتخفي حاجة من غير ما
 * تقول بتبقى بتكدب بالصمت (DESIGN قاعدة ٨).
 *
 * **الملف ده صافي.**
 * ==========================================================================
 */

export type IssueOrder = {
  /** تاريخ الأوردر — المشاكل بتتفلتر بيه */
  order_date?: string | null;
  created_at?: string | null;
};

const day = (v: string | null | undefined) => String(v ?? "").slice(0, 10);

/** الأوردر ده يدخل شاشات المشاكل؟ */
export function withinIssueWindow(
  order: IssueOrder,
  since: string | null | undefined
): boolean {
  const from = day(since);
  if (!from) return true;
  const at = day(order.order_date) || day(order.created_at);
  // من غير تاريخ = بيدخل — إخفاء حاجة مالهاش تاريخ بيخفي مشكلة حقيقية
  return at === "" || at >= from;
}

/** اللي بيتعرض في الشاشة جنب العدّاد */
export function issueWindowNote(
  since: string | null | undefined,
  hidden: number
): string | null {
  if (!day(since) || hidden <= 0) return null;
  return `${hidden} أقدم من التاريخ المختار في الإعدادات — متخفيين`;
}
