// ⚠️⚠️ **كل رنّة من بوسطة بتشغّل مزامنة كاملة.** المزامنة بتجيب **كل**
// شحنات البيزنس من بوسطة (٣٨٧ شحنة عند مينيز، ٣٧٤ عند ٢ سِك) وتقارنها
// بكل أوردراته.
//
// ده كان مقبول لما الرنّة كانت نادرة. بس بعد ما بقينا بنبعت `webhookUrl`
// مع **كل شحنة** (١٨ أغسطس)، بوسطة بترنّ على كل تغيير في كل شحنة —
// والشحنة الواحدة بتعدّي بكذا حالة في اليوم.
//
// يعني يوم شغل عادي = **عشرات المزامنات الكاملة**، وكل واحدة بتضرب API
// بوسطة بمئات الشحنات. ده بيتعب بوسطة وبيتعبنا، ومافيش منه فايدة: عشر
// رنّات في دقيقة بتقرا نفس الداتا تقريبًا.
//
// **المهلة دقيقة**: مش أطول عشان التحديث يفضل «فوري» في إحساس المستخدم،
// ومش أقصر عشان الرشقة الواحدة تتجمّع في مزامنة واحدة.
//
// **المهلة بقت خمس دقايق** (كانت دقيقة لحد ٩ نوفمبر ٢٠٢٦): اللفة الواحدة
// بتاخد ٣٣ ثانية، ودقيقة كانت بتسمح بـ٩ ساعات معالجة في الشهر — ودي
// لوحدها كانت بتاكل نص الباقة المجانية. اقرا `PERIODIC_COOLDOWN_MS` تحت.
//
// **واللي بيتأجّل مابيضيعش**: المزامنة اللي بعدها بتقرا الحالة الحالية من
// بوسطة — مش سجل أحداث. فأي تغيير حصل في المهلة بيتلقط في اللفة اللي
// بعدها، وأسوأ حالة اللفة الدورية كل ساعة.
//
// **الملف ده صافي** — مافيش شبكة ولا قاعدة بيانات.
// ==========================================================================

export const COOLDOWN_MS = 5 * 60_000;

export type CooldownDecision =
  | { run: true }
  | { run: false; waitMs: number };

/**
 * نزامن دلوقتي ولا نستنى؟
 *
 * `lastRunAt` فاضية معناها **مافيش مزامنة اتسجّلت** — يبقى نزامن. مش
 * معناها إن المزامنة قريبة.
 */
export function shouldSyncNow(
  lastRunAt: string | Date | null | undefined,
  now: Date = new Date(),
  cooldownMs: number = COOLDOWN_MS
): CooldownDecision {
  if (!lastRunAt) return { run: true };

  const last = lastRunAt instanceof Date ? lastRunAt : new Date(lastRunAt);
  const t = last.getTime();

  // تاريخ مش مفهوم؟ **نزامن** — الأمان إننا نشتغل مش إننا نسكت
  if (!Number.isFinite(t)) return { run: true };

  const since = now.getTime() - t;

  // ⚠️ **التاريخ في المستقبل بيتعامل كأنه دلوقتي.**
  // ساعة السيرفر وساعة الداتابيز ممكن يفرقوا ثواني، وبدون ده الفرق بالسالب
  // كان هيعدّي المهلة ويخلّي كل رنّة تزامن.
  if (since < 0) return { run: false, waitMs: cooldownMs };

  if (since >= cooldownMs) return { run: true };
  return { run: false, waitMs: cooldownMs - since };
}

/**
 * ==========================================================================
 * ⚠️⚠️ **المهلة الدورية** — فيرسل وقّف المشروع (٩ نوفمبر ٢٠٢٦)
 * --------------------------------------------------------------------------
 * الباقة المجانية حدها ٤ ساعات `Fluid Active CPU` في الشهر، والمشروع
 * وصل **٤س ٤٥د** فاتقفل. والقياس على ٣٠ يوم:
 *
 *   • `bosta`  الدورية      ٥٬٧٦٤ لفة · ٢٢.٢ ساعة
 *   • `bosta-webhook`         ٩٧٧ لفة · ٩.٠ ساعات (٣٣ ثانية للفة)
 *   • `shopify`             ٨٬٦٦٨ لفة · بتجيب صفر كل مرة
 *
 * الكرون اللي برّه بينده كل ١٥ دقيقة، **والراوت الدوري ماكانش فيه مهلة
 * خالص** — كل نداء بيزامن كل بيزنس كامل (٥٦٥ شحنة من بوسطة).
 *
 * ⚠️ **والمهلة هنا مش في الكرون بقصد.** الكرون برّه السيستم ومش تحت
 * إيدنا، ولو حد غيّره أو ضاف واحد تاني المشكلة بترجع. الحارس في الكود
 * بيمسك أي نداء مهما كان مصدره.
 *
 * **ساعة للدورية**: الويب هوك بيوصل التغييرات فورًا، فالدورية دي شبكة
 * أمان لو رنّة ضاعت — مش المصدر الأساسي.
 * ==========================================================================
 */
export const PERIODIC_COOLDOWN_MS = 60 * 60_000;
