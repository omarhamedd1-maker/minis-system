// نصوص التنبيهات
// --------------------------------------------------------------------------
// كانت جوّه ملف تليجرام، وتليجرام اتشال — بس النصوص نفسها لسه مستخدمة
// مع إشعارات الموبايل. الوسوم (<b> و<code>) بتتشال قبل الإشعار في
// `lib/push/notify.ts`، فسيبها زي ما هي.
//
// **الشكل واحد في كل إشعار من غير استثناء**: رقم الأوردر في السطر الأول،
// واسم العميل في السطر التاني تحته. السطر الأول بيبقى عنوان الإشعار على
// الموبايل والباقي جسمه، فالاسم بيبان قبل أي تفصيلة تانية.
//
// **ورقم الشحنة مابيدخلش أي إشعار.** رقم من ٨ أرقام مالوش أي معنى على شاشة
// القفل، وكان بياخد سطر من مساحة ضيقة أصلاً — واللي عايزه بيلاقيه في الأوردر.
// ==========================================================================

import { exceptionAdvice, shortReason } from "./bosta/exception";

/**
 * أول سطرين في أي إشعار.
 * لو مافيش اسم بنسيب السطر فاضي عشان الشكل مايختلفش والجسم يفضل مفصول.
 *
 * ⚠️ **الإيموجي في آخر السطر مش أوله — وده مقصود.**
 * التليفون بيحدد اتجاه كل سطر من **أول حرف حقيقي فيه**. الإيموجي مالوش
 * اتجاه، فالسطر اللي بيبدأ بيه بيتحسب إنجليزي ويترمي على الشمال — والباقي
 * عربي على اليمين. النتيجة كانت إشعار نصه شمال ونصه يمين.
 * أول حرف عربي = السطر كله يمين زي باقي الإشعار.
 */
export function alertHead(
  icon: string,
  headline: string,
  customerName: string | null | undefined
): string[] {
  return [`<b>${headline}</b> ${icon}`.trim(), String(customerName ?? "").trim()];
}

export type FailedDeliveryAlert = {
  orderNumber: string | number | null;
  customerName: string | null;
  customerPhone: string | null;
  /** سبب بوسطة لو كتبته — هو اللي بيحدد الجملة الأخيرة */
  reason: string | null;
  /** رجعت خلاص ولا لسه في الطريق لينا */
  arrived: boolean;
  /** بوسطة واقفة ومستنية قرار مننا — مش راجعة (لسه) */
  waiting?: boolean;
};

/**
 * رسالة "العميل مستلمش".
 * دي أهم تنبيه في السيستم — معناها بضاعة راجعة وفلوس ماوصلتش، ولازم حد
 * يكلّم العميل **دلوقتي** قبل ما الشحنة توصل المخزن وتبقى خسارة مؤكدة.
 *
 * ولما بوسطة تكون واقفة مستنية قرار، الجملة بتتكتب من سبب الوقوف الحقيقي
 * (`exceptionAdvice`) — مش جملة واحدة محفوظة لكل الحالات.
 */
export function failedDeliveryMessage(a: FailedDeliveryAlert): string {
  const headline = a.waiting
    ? `أوردر ${a.orderNumber ?? "—"} ${exceptionAdvice(a.reason).title}`
    : a.arrived
      ? `أوردر ${a.orderNumber ?? "—"} رجع ومتسلّمش`
      : `أوردر ${a.orderNumber ?? "—"} العميل مستلمش`;

  // **الاسم والتليفون في سطر واحد.** الآيفون بيعرض ٤ سطور بس على شاشة
  // القفل، فكل سطر بيتحرق معناه إن السطر اللي بيقول "اعمل إيه" بيتقص.
  const who = [a.customerName?.trim(), a.customerPhone?.trim()]
    .filter(Boolean)
    .join(" · ");

  const lines = alertHead(a.waiting ? "🛑" : a.arrived ? "📦" : "⚠️", headline, who);

  // السبب من غير مقدمة ومن غير التواريخ — «العميل رفض يستلم» بتقول نفسها،
  // والتفاصيل كاملة في شاشة الأوردر
  const reason = shortReason(a.reason);
  if (reason) lines.push(reason);

  // ⚠️ **مفيش سطر بيقول «اعمل إيه».** كان فيه واحد («كلّمه قبل ما الشحنة
  // ترجع المخزن» · «راجع المخزون والفلوس») واتشال بطلب عمر: هو صاحب
  // المتجر وعارف شغله، والنصيحة كانت بتاكل سطر من المعلومة — وشاشة قفل
  // الآيفون بتعرض ٤ سطور بس.
  return lines.join("\n");
}

/** رسالة "المزامنة واقفة" — دي مالهاش عميل، فمفيش سطر تاني */
export function syncDownMessage(detail: string): string {
  const lines = ["<b>المزامنة مع بوسطة واقفة</b> 🔴", detail];
  lines.push("الحالات والتحصيل مش بيتحدّثوا — الأرقام قديمة");
  return lines.join("\n");
}

/**
 * رسالة «استيراد أوردرات شوبيفاي وقف» — دي لصاحب المتجر، مش عن أوردر معين.
 *
 * ⚠️ **السبب بيتكتب زي ما شوبيفاي ردّت بيه.** «Invalid API key» هي الجملة
 * اللي بتقول إن التوكن باظ — يعني الربط محتاج يتعمل من أول وجديد، مش
 * مجرد «فيه تأخير».
 *
 * ⚠️ **والرسالة بتتبعت مرة في اليوم** (التاج `shopify-import-<اليوم>`) —
 * تكرارها كل ربع ساعة هو بالظبط اللي ضرب عمر يوم ٢٠ أغسطس. ولو جدول
 * السجل مش موجود أصلًا، المسار اللي بيناديها بيسكت خالص.
 */
export function shopifyImportFailMessage(reason: string): string {
  return [
    "<b>استيراد أوردرات شوبيفاي وقف</b> 🔴",
    reason,
    "الأوردرات الجديدة مش هتنزل — افتح الإعدادات واربط المتجر تاني",
  ].join("\n");
}
