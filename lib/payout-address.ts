/**
 * ==========================================================================
 * عنوان استقبال إيميل التحويل (TRANSFERS §٣)
 * --------------------------------------------------------------------------
 * لكل بيزنس عنوان سري: `transfers+<مفتاح>@<الدومين>`. المشتري بيعمل قاعدة
 * واحدة في جيميل: «الجاي من no-reply@bosta.co وعنوانه Cashout Receipt →
 * حوّله للعنوان ده».
 *
 * ⚠️ **المفتاح سر** — اللي يعرفه يقدر يبعت إيميل. بس معرفته لوحدها مش
 * كفاية: الإيميل لازم يعدّي التوقيع والمطابقة ورقم الفاتورة (§٤).
 *
 * ⚠️ **وجيميل مابيحوّلش لعنوان جديد غير بعد كود تأكيد** بيوصل للعنوان ده
 * — يعني بيوصل عندنا إحنا. فالشاشة لازم تعرضه، وإلا الإعداد بيقف.
 *
 * **الملف ده صافي** — نصوص بس.
 * ==========================================================================
 */

export const INBOX_USER = "transfers";

/** العنوان السري للبيزنس — و`null` لو المفتاح أو الدومين ناقص */
export function payoutAddress(
  key: string | null | undefined,
  domain: string | null | undefined
): string | null {
  const k = String(key ?? "").trim();
  const d = String(domain ?? "").trim().replace(/^https?:\/\//, "").replace(/\/.*$/, "");
  if (!k || !d) return null;
  return `${INBOX_USER}+${k}@${d}`;
}

/**
 * المفتاح من العنوان اللي الإيميل وصل عليه.
 *
 * ⚠️ **بيقرا اللي بعد `+` بس** — مزوّدين البريد بيضيفوا اسم العرض
 * (`"اسم" <transfers+abc@x.com>`) وبيغيّروا حالة الأحرف.
 */
export function keyFromAddress(to: string | null | undefined): string | null {
  const raw = String(to ?? "");
  const inAngles = /<([^>]+)>/.exec(raw)?.[1] ?? raw;
  const at = inAngles.trim().toLowerCase();
  const m = new RegExp(`^${INBOX_USER}\\+([a-z0-9]+)@`).exec(at);
  return m ? m[1] : null;
}

const isGmailConfirm = (text: string) =>
  /gmail|forwarding|تحويل البريد|confirmation/i.test(text);

/**
 * ⚠️⚠️ **رابط التأكيد هو الأساس، مش الكود.**
 *
 * جيميل بيعرض في صفحة الإعدادات زرار «Verify» من غير أي خانة إدخال —
 * يعني مستني إنك **تفتح الرابط**، مش تكتب رقم. والرسالة نفسها فيها
 * رابطين:
 *
 *   `mail/vf-…` ← **التأكيد** (verify forwarding)
 *   `mail/uf-…` ← **الرفض** (اللي بيلغي الطلب)
 *
 * ⚠️ **فالرابط الغلط بيلغي الإعداد بدل ما يعمله** — عشان كده بنمسك
 * `vf-` بالاسم مش «أول رابط جيميل».
 */
export function gmailConfirmLink(subject: string, body: string): string | null {
  const text = `${subject ?? ""}\n${body ?? ""}`;
  if (!isGmailConfirm(text)) return null;
  const m = /https?:\/\/mail\.google\.com\/mail\/vf-[^\s"'<>]+/i.exec(text);
  if (!m) return null;
  // الجسم HTML، فالرموز المهرّبة بترجع زي ما هي
  return m[0].replace(/&amp;/g, "&");
}

/**
 * ⛔⛔ **«كود تأكيد جيميل» اتشال بالكامل — ماكانش موجود أصلًا.**
 *
 * الدالة القديمة كانت بتدوّر على أول رقم من ٥ لـ١٢ خانة في الرسالة،
 * وبترجّع **١٨٤٩٧٣** كل مرة — وده **رقم مقال المساعدة** في آخر
 * الإيميل (`support.google.com/mail/bin/answer.py?answer=184973`)،
 * مش كود.
 *
 * ورسالة تأكيد التحويل من جيميل **مافيهاش كود من الأساس**: التأكيد
 * برابط، وصفحة الإعدادات عند جيميل بتوري «Verify» من غير خانة إدخال.
 *
 * ⚠️ فالرقم ده كان أسوأ من لا حاجة: شاشة بتدّي رقم شكله صح، وحد قاعد
 * نص ساعة يدوّر على مكان يكتبه فيه. **مايترجّعش تاني ولا كـ«احتياطي»** —
 * الاحتياطي اللي بيضلل مش احتياطي.
 */

/**
 * خطوات الإعداد — بتتعرض في الشاشة زي ما هي.
 *
 * ⚠️ **الخطوة ٣ رابط مش كود** — جيميل بيوري «Verify» من غير خانة إدخال،
 * والرابط بيوصل عندنا إحنا مش عنده. من غير ما الشاشة تعرضه، الإعداد
 * بيقف عند خطوة مفيهاش حاجة تتكتب.
 */
export function setupSteps(address: string): string[] {
  return [
    "افتح جيميل ← الإعدادات ← Forwarding and POP/IMAP",
    `ضيف العنوان ده: ${address}`,
    // ⚠️ نص عادي — بيتعرض في `li` زي ما هو، والنجوم بتبان نجوم
    "رسالة التأكيد بتوصل عندنا إحنا مش عندك — استنى دقيقة واعمل تحديث، وهيطلع زرار «أكّد التحويل» تحت",
    "دوس الزرار (وجيميل هيقول Confirmation Success)، وبعدين ارجع لجيميل واختار العنوان ده",
    "وآخر حاجة: Filters ← قاعدة جديدة — من no-reply@bosta.co وفيها Cashout Receipt ← حوّلها للعنوان ده",
  ];
}
