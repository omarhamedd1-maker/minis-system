// ==========================================================================
// الدفع المقدم — بيوفّر كام فعلًا
// --------------------------------------------------------------------------
// «زوّد الدفع المسبق» نصيحة بيقولها كل حد. الناقص هو **الرقم**: العميل
// اللي بيدفع أونلاين بيوفّر عليك كام بالظبط؟ من غير الرقم ده، أي خصم
// بتديه عشان تشجّع الدفع المقدم تخمين — ممكن يكون أكبر من اللي بيوفّره.
//
// ⚠️⚠️ **الرقم بيتحسب من الرجوع، مش من مقارنة الطريقتين.** عند مينيز فيه
// **٦ أوردرات مدفوعة مقدم بس** (٤ منهم خلصوا، صفر رجعوا). «صفر رجوع» على
// ٤ أوردرات **مش دليل** — ده نفس فخ «١٠٠٪ رجوع على أوردر واحد» بالظبط.
//
// اللي عندنا رقم قوي فعلًا هو **رجوع الدفع عند الاستلام**: ٥٠ من ٣٠١
// أوردر خالص = ١٦٫٦٪، على عيّنة كبيرة. والحسبة بتقول:
//
//   الأوردر اللي بيتدفع عند الاستلام بيحمل **خسارة متوقعة** = احتمال
//   الرجوع × تكلفة الشحنة الرايحة والجاية. الأوردر المدفوع مقدم مابيحملهاش
//   — الفلوس معاك قبل ما الشحنة تتحرك.
//
// ⚠️ **والحسبة مابتقولش إن الدفع المقدم مابيرجعش خالص** — بيرجع، بس
// **الفلوس معاك** فالخسارة شحن بس مش شحن وبضاعة معلّقة.
//
// **الملف ده صافي** — بياخد أرقام وبيرجّع أرقام.
// ==========================================================================

/** أقل عدد أوردرات خالصة عشان نسبة الرجوع تبقى ليها معنى */
export const MIN_SETTLED = 30;

export type PrepaidInput = {
  /** أوردرات الدفع عند الاستلام اللي خلصت (اتسلّمت أو رجعت) */
  codSettled: number;
  /** منهم كام رجع */
  codReturned: number;
  /** أوردرات مدفوعة مقدم — للعرض بس */
  prepaidCount: number;
  /**
   * تكلفة الشحنة الراجعة عليك.
   *
   * ⚠️ **رايح وجاي** — بوسطة بتاخد الرايح كامل والجاي جزء منه. الرقم ده
   * بيتقرا من رسومك الحقيقية مش من تقدير.
   */
  returnShippingCost: number;
  /** متوسط قيمة الأوردر — للمقارنة بالخصم */
  averageOrder: number;
};

export type PrepaidValue = {
  /** نسبة رجوع الدفع عند الاستلام — و`null` لو الأرقام قليلة */
  codReturnRate: number | null;
  /**
   * الخسارة المتوقعة على كل أوردر بيتدفع عند الاستلام.
   *
   * = احتمال الرجوع × تكلفة الشحنة الرايحة والجاية
   */
  lossPerCod: number | null;
  /** اللي اتحرق فعلًا على الشحنات الراجعة */
  burned: number;
  /**
   * أكبر خصم يستاهل تديه عشان العميل يدفع مقدم.
   *
   * ⚠️ **فوقه بتخسر** — الخصم بيبقى أكبر من اللي بيوفّره.
   */
  worthDiscount: number | null;
  /** الخصم ده كام ٪ من متوسط الأوردر */
  worthPercent: number | null;
  prepaidCount: number;
  /** ⚠️ العيّنة صغيرة؟ */
  weak: boolean;
};

export function prepaidValue(input: PrepaidInput): PrepaidValue {
  const settled = Math.max(0, Math.floor(input.codSettled));
  const returned = Math.max(0, Math.floor(input.codReturned));
  const ship = Math.max(0, Number(input.returnShippingCost) || 0);
  const avg = Math.max(0, Number(input.averageOrder) || 0);

  const weak = settled < MIN_SETTLED;

  // ⚠️ **النسبة مابتتعرضش على أرقام قليلة** — نفس قاعدة كل الشاشات
  const rate =
    weak || settled === 0
      ? null
      : Math.round((returned / settled) * 1000) / 10;

  const loss = rate === null ? null : Math.round((rate / 100) * ship * 100) / 100;

  return {
    codReturnRate: rate,
    lossPerCod: loss,
    burned: Math.round(returned * ship),
    // الخصم اللي يستاهل = اللي بتوفّره بالظبط
    worthDiscount: loss === null ? null : Math.round(loss),
    worthPercent:
      loss === null || avg <= 0 ? null : Math.round((loss / avg) * 1000) / 10,
    prepaidCount: Math.max(0, Math.floor(input.prepaidCount)),
    weak,
  };
}

/**
 * الجملة اللي بتتعرض.
 *
 * ⚠️ **بتقول الرقم ومن فين جه** — من غير «اعمل كذا». والخصم بيتقال
 * كـ«يستاهل» مش كـ«اعمله».
 */
export function prepaidLine(v: PrepaidValue): string {
  if (v.codReturnRate === null) {
    return "لسه مافيش أوردرات خالصة كفاية عشان نحسب.";
  }
  return [
    `${v.codReturnRate}% من أوردرات الدفع عند الاستلام بترجع.`,
    `يعني كل أوردر بيتدفع عند الاستلام شايل خسارة متوقعة ${v.lossPerCod} جنيه شحن.`,
  ].join(" ");
}
