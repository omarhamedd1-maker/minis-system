// ==========================================================================
// سطر السجل في صفحة الأوردر — أقصر ما يمكن
// --------------------------------------------------------------------------
// نص السجل بيتخزّن مرة واحدة وبيتعرض في مكانين: **سجل النشاط العام** (لازم
// يقول أنهي أوردر) و**سجل الأوردر نفسه** (رقم الأوردر مكتوب فوق الصفحة،
// فتكراره في كل سطر بيخلّي العين تدوّر على المعلومة وسط كلام معروف).
//
// الملف ده بيقصّ الجزء المكرر **وقت العرض بس** — الجدول مابيتغيّرش، فالسجل
// القديم بيتقصّر لوحده ومفيش هجرة داتا.
//
// ⚠️ **بنشيل رقم الأوردر ده بالذات مش أي رقم.** «مسح منتج من أوردر ١٣٦٧»
// جوّه صفحة ١٣٦٧ بتبقى «مسح منتج»، بس نفس السطر في السجل العام بيفضل كامل.
//
// ⚠️⚠️ **ومافيش `new RegExp` بنص متغيّر هنا بقصد.** الباكسلاشات بتضيع وإحنا
// بنكتب الملف من الطرفية، فـ`\b` بتبقى حرف باكسبيس والمطابقة عمرها ما تنجح
// **من غير أي خطأ**. الغلطة دي حصلت مرتين قبل كده — فالقص هنا بمقارنة نصوص
// عادية، والحدود بتتفحص بالحرف اللي بعد الرقم.
//
// **الملف ده صافي** — نص داخل ونص خارج.
// ==========================================================================

/**
 * أسماء حالات بوسطة بالعربي.
 *
 * ⚠️ **بوسطة بتبعت الاسم إنجليزي وإحنا بنخزّنه زي ما هو.** السطر اللي بيقول
 * `Received at warehouse` وسط سجل عربي بيتقري كأنه عطل. اللي مش في القايمة
 * بيتعرض زي ما جه — أحسن من «حالة غير معروفة».
 */
const BOSTA_STATE_AR: Record<string, string> = {
  "Pickup requested": "طلبنا الاستلام",
  "Route Assigned": "اتحدد المندوب",
  "Picked up": "المندوب استلمها",
  "Picked up from business": "المندوب استلمها مننا",
  "Received at warehouse": "في مخزن بوسطة",
  "In transit between Hubs": "بين فروع بوسطة",
  Processing: "بيتجهّز",
  Delivered: "اتسلّمت",
  "Returned to business": "رجعت لنا",
  Exception: "وقفت — محتاجة تصرّف",
  Lost: "ضايعة",
  Archived: "مقفولة",
};

export function bostaStateAr(name: string): string {
  return BOSTA_STATE_AR[name.trim()] ?? name.trim();
}

/** المسافات الزيادة والعلامات اليتيمة اللي بتفضل بعد القص */
function tidy(text: string): string {
  return text.split(/\s+/).join(" ").replace(/^[\s:،-]+|[\s:،-]+$/g, "").trim();
}

/** حروف الجر اللي بتيجي قبل «أوردر» — الأطول الأول عشان «لـ» ماتتاكلش بـ«ل» */
const PREPS = ["في ", "من ", "لـ", "بـ", "ل", "ب", ""];

/**
 * بيشيل «أوردر ١٣٦٧» ومعاها حرف الجر اللي قبلها.
 *
 * ⚠️ **الرقم اللي جوّه رقم أطول مايتشالش** — «أوردر ١٣٦٧٠» مش أوردرنا،
 * فبنتأكد إن اللي بعد الرقم مش رقم تاني.
 */
function stripOrderNumber(text: string, n: string): string {
  let out = text;
  for (const prep of PREPS) {
    const needle = `${prep}أوردر ${n}`;
    for (;;) {
      const at = out.indexOf(needle);
      if (at < 0) break;
      const after = out[at + needle.length];
      if (after && after >= "0" && after <= "9") break;
      out = out.slice(0, at) + " " + out.slice(at + needle.length);
    }
  }
  return out;
}

/**
 * نص السطر جوّه صفحة الأوردر.
 *
 * بيرجّع النص الأصلي لو مالقاش حاجة يقصّها — **مابيرجّعش فاضي أبدًا**، السطر
 * الفاضي في السجل أوحش من السطر الطويل.
 */
export function shortLogText(
  summary: string | null | undefined,
  orderNumber: string | null | undefined
): string {
  const raw = String(summary ?? "").trim();
  if (!raw) return "";

  const n = String(orderNumber ?? "").trim();

  // حالة بوسطة: «شحنة أوردر ١٣٦٤ عند بوسطة: Picked up (كانت …)»
  // الحالة القديمة موجودة في السطر اللي فوقه، فمالهاش لازمة تتكرر.
  const bosta = raw.match(/عند بوسطة:\s*([^(]+?)\s*(?:\(كانت.*\))?$/);
  if (bosta) return `بوسطة: ${bostaStateAr(bosta[1])}`;

  // «تحصيل أوردر ١٣٧٤ عند بوسطة اتغيّر من ٧٣٩ لـ ١٣٨٨»
  const cod = raw.match(/تحصيل .*عند بوسطة اتغيّر من\s+(\S+)\s+لـ\s+(\S+)/);
  if (cod) return `التحصيل: ${cod[1]} ← ${cod[2]}`;

  const rules: [RegExp, string][] = [
    [/^غيّر حالة أوردر\s+\S+\s+لـ\s+/, "الحالة: "],
    [/^غيّر شحن أوردر\s+\S+\s+لـ\s+/, "الشحن: "],
    [/^غيّر خصم أوردر\s+\S+\s+لـ\s+/, "الخصم: "],
    [/^غيّر طريقة الدفع لأوردر\s+\S+\s+/, "طريقة الدفع "],
    [/^تعديل أوردر\s+\S+\s+اتبعت لشوبيفاي$/, "اتبعت لشوبيفاي"],
    [/^بعت أوردر لبوسطة كشحنة$/, "اتبعت لبوسطة"],
  ];
  for (const [re, to] of rules) {
    if (re.test(raw)) return tidy(raw.replace(re, to));
  }

  if (n) {
    const stripped = stripOrderNumber(raw, n);
    if (stripped !== raw) return tidy(stripped) || raw;
  }

  return raw;
}
